"""Syslog objects in, keepalived's IPVS virtual servers out (Fas 19b, B256).

Community HAProxy 3.4 receives syslog over UDP only in `log-forward`, which
sends each message on from the node's own address. The receivers behind -
Splunk, Graylog, Wazuh, Grafana Alloy - name a sender by the address its
messages come from, so a `syslog` object is served by the kernel's IPVS
instead: keepalived's `virtual_server`, in NAT mode, one packet at a time
(`ops`). The kernel rewrites only the destination, the receiver sees the
sender, and syslog over UDP never answers, so nothing has to route back
through the node. Measured in the lab, 26-10-07: the sender's address at the
receiver, 3514/3513 of 7027 messages in turn, a reload with a changed virtual
server and a failover under 200 messages a second without one lost.

**One file for the cluster**, `managed/keepalived/ipvs.conf`, the node's
`/etc/keepalived/ipvs.conf`, included at the top level of `keepalived.conf` -
beside the address list (B57), and like it written by the generator alone.
Always written: without a syslog object it holds no virtual server, and
installing it removes the ones the previous release had. A release without the
file is one from before this layer, which the node leaves alone.

**What is not here**: everything VRRP. The file holds virtual servers and
nothing else, so a mistake in it can stop the forwarding but not move an
address - and the node tests it with `keepalived --config-test` before
reloading.

Every value written has been held to a pattern by the model or comes from the
cluster's own configuration: addresses parse as addresses, names match the
model's name pattern, numbers are numbers. Nothing a person typed reaches the
file as text.
"""

from __future__ import annotations

import ipaddress
from collections.abc import Sequence
from dataclasses import dataclass

from haprion.config import Vip
from haprion.proxy_model import Backend, Health, Proxy, duration_ms

FILE = "ipvs.conf"
#
# The line above each virtual server, which the node's status reads back to
# name the kernel's services: IPVS knows an address and a port, the metrics
# keep a pool and its servers. The receivers are `s1`, `s2`, ... in the order
# they are written, as HAProxy's and dnsdist's members are. Both names hold to
# the model's name pattern, so the line has one reading.
#
NAMES = "# object {object}, pool {pool}"

HEADER = """\
#
# Generated by Haprion from this cluster's syslog objects. Do not edit
# on the node: the next deploy overwrites this file.
#
# Included at the top level of keepalived.conf, outside every vrrp_instance.
# It holds IPVS virtual servers and nothing that decides VRRP ownership.
#
"""

#
# The model's balancing names, as IPVS's schedulers. See `SYSLOG_BALANCE`.
#
SCHEDULERS = {"roundrobin": "rr", "source": "mh", "firstAvailable": "fo"}

#
# How long a udp check waits for an ICMP error before counting the receiver
# up. keepalived's own default, written out: its manual asks for at least four
# seconds, since a receiver whose host is gone is reported by the node's own
# ARP timing out (keepalived.conf(5), 2.3.4). A tcp check waits one interval,
# as HAProxy's does (`inter`).
#
UDP_CONNECT_TIMEOUT = "5"


@dataclass(frozen=True, slots=True)
class IpvsLayer:
    file: str
    """`managed/keepalived/ipvs.conf`, and `/etc/keepalived/ipvs.conf` on the node."""

    parts: dict[str, dict[str, str]]
    """Per object, the release manifest's four parts (see `object_manifest`)."""


def _address(value: str) -> ipaddress.IPv4Address | ipaddress.IPv6Address:
    return ipaddress.ip_address(value.strip("[]"))


def _seconds(value: str) -> str:
    """A duration the model accepted, as keepalived's seconds: `2`, `0.5`."""

    milliseconds = duration_ms(value)
    whole, rest = divmod(milliseconds, 1000)
    return str(whole) if not rest else f"{milliseconds / 1000:g}"


def _checker(health: Health) -> list[str]:
    """The checker block inside each real server, or none when the pool is unchecked.

    Without a checker keepalived holds the receiver up, which is what an
    unchecked pool means everywhere else.
    """

    if health.type == "disabled":
        return []
    if health.type == "udp":
        name, timeout = "UDP_CHECK", UDP_CONNECT_TIMEOUT
    else:
        name, timeout = "TCP_CHECK", _seconds(health.interval)
    body = [f"connect_timeout {timeout}", f"retry {health.fall - 1}"]
    if health.type == "tcp" and health.port is not None:
        body.insert(0, f"connect_port {health.port}")
    return [f"{name} {{", *(f"    {line}" for line in body), "}"]


def _real_servers(vip: Vip, proxy: Proxy, pool: Backend) -> list[str]:
    family = _address(vip.address).version
    lines: list[str] = []
    checker = _checker(pool.health)
    count = len(pool.servers)
    for index, server in enumerate(pool.servers):
        address = _address(server.host)
        if address.version != family:
            raise ValueError(
                f"{proxy.name} sits on an IPv{family} address and cannot forward to "
                f"{server.host}: IPVS in NAT mode keeps the address family"
            )
        #
        # `fo` sends to the receiver of the highest weight, and between equal
        # weights to the first in the kernel's list (`ip_vs_fo_schedule`,
        # Linux 6.12) - which is the order keepalived added them in, and a
        # receiver it took out and put back is added last. Falling weights in
        # the object's order are what make the first receiver that is up the
        # one that gets the messages, whatever came and went before.
        #
        weight = [f"weight {count - index}"] if pool.balance == "firstAvailable" else []
        lines += [
            f"real_server {address} {server.port} {{",
            *(f"    {line}" for line in [*weight, *checker]),
            "}",
        ]
    return lines


def _virtual_server(vip: Vip, proxy: Proxy) -> tuple[str, list[str]]:
    port = proxy.listen.port
    if port is None:
        raise ValueError(f"{proxy.name} is a syslog object without a port")
    pool = proxy.backends[proxy.backend or ""]
    listener = f"{_address(vip.address)} {port}"
    head = [
        "protocol UDP",
        "lvs_method NAT",
        f"lvs_sched {SCHEDULERS[pool.balance]}",
        "ops",
    ]
    if pool.health.type != "disabled":
        head.append(f"delay_loop {_seconds(pool.health.interval)}")
    servers = _real_servers(vip, proxy, pool)
    block = [
        NAMES.format(object=proxy.name, pool=proxy.backend),
        f"virtual_server {listener} {{",
        *(f"    {line}" for line in [*head, *servers]),
        "}",
    ]
    return listener, block


def render(placed: Sequence[tuple[Vip, Proxy]]) -> IpvsLayer:
    """The cluster's IPVS virtual servers, from its syslog objects and where they sit.

    `placed` is (VIP, object) per syslog object, in name order, as `generate`
    decided them. Empty gives the header alone: no virtual server, which is
    what removes the previous release's from the nodes.
    """

    blocks: list[str] = []
    parts: dict[str, dict[str, str]] = {}
    for vip, proxy in placed:
        listener, block = _virtual_server(vip, proxy)
        blocks += ["", *block]
        parts[proxy.name] = {
            "backends": "\n".join(block[2:-1]) + "\n",
            "routing": "",
            "listener": f"{listener} udp\n",
            "certificate": "",
        }
    return IpvsLayer(file=HEADER + "".join(f"{line}\n" for line in blocks), parts=parts)
