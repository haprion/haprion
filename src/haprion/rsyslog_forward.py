"""rsyslog's forwarding of the traffic log to the cluster's external receivers (B286).

HAProxy writes one structured line per request to the node's syslog socket
(B287), and rsyslog writes it to the node's day file and sends it on. A memory
ring in HAProxy used to send it: it dropped what did not fit, and only the
receiver could tell. Here each receiver has a queue on the node's disk, sized
by `disk_mib` (B288): a receiver that is away or slower than the traffic gets
what fits when it reads again, and what does not is counted where the node
status can read it (B289).

Measured with rsyslog 8.2512 on one core (26-10-12): 25 000 lines a second
forwarded and written to file at 9 % of the core; a queue filled while the
receiver was away was sent in about a second once it came back, and survived
a stop of rsyslog on the way.

The file is generated whole on every publish into `managed/rsyslog/`, and
the node's deploy copies it to `/etc/rsyslog.d/haprion/`, where rsyslog may
read it (AppArmor does not let it read the release), checks it with
`rsyslogd -N1` and restarts rsyslog when it changed.
"""

from __future__ import annotations

from collections.abc import Sequence

from haprion.cluster_settings import LogTarget

FILE = "forward.conf"
#
# The names rsyslog's statistics report: the action's own, and its queue's as
# `<name> queue` and `<name> queue[DA]` for the part on disk.
#
ACTION_PREFIX = "haprion-"
TEMPLATE = "haprion-forward"
#
# The queues live where the distribution's rsyslog keeps its own
# ($WorkDirectory, /var/spool/rsyslog on Ubuntu), named after the action.
#
SYSTEM_CA = "/etc/ssl/certs/ca-certificates.crt"

HEADER = (
    "#",
    "# Generated by Haprion. Do not edit.",
    "#",
    "# Copied to /etc/rsyslog.d/haprion/ by every deploy that carries it and",
    "# removed by every deploy that does not; an edit there lasts until then.",
    "#",
)


def action_name(target: LogTarget) -> str:
    return f"{ACTION_PREFIX}{target.name}"


def _action(target: LogTarget) -> list[str]:
    parameters = [
        'type="omfwd"',
        f'name="{action_name(target)}"',
        f'target="{target.address}"',
        f'port="{target.port}"',
        'protocol="tcp"',
        #
        # Framed by length, as RFC 6587 and the ring before it did, so a record
        # holding a newline cannot be split by the receiver.
        #
        'TCP_Framing="octet-counted"',
        f'template="{TEMPLATE}"',
    ]
    if target.tls:
        #
        # The chain against the system's trust store, and no name: what the
        # ring checked (`verify required ca-file @system-ca`). The receiver is
        # named by its address, which a certificate rarely carries.
        #
        parameters += [
            'StreamDriver="gtls"',
            'StreamDriverMode="1"',
            'StreamDriverAuthMode="x509/certvalid"',
            f'StreamDriver.CAFile="{SYSTEM_CA}"',
        ]
    parameters += [
        #
        # A queue of its own, in memory and spilling to disk, so a receiver
        # that does not read holds up nothing but itself.
        #
        'queue.type="LinkedList"',
        f'queue.filename="{action_name(target)}"',
        #
        # Room in memory while the disk part catches up. rsyslog's default
        # holds 1 000 lines and spills to disk at 900; with the node's one
        # core busy serving traffic the disk part fell behind and the memory
        # part dropped (1 048 lines at 25 000 a second on internal, 26-10-12;
        # 800 when reproduced with rsyslog sharing a loaded core). Spilling
        # from 2 000 into 20 000 dropped none in three runs of 375 000 to
        # 500 000 lines on a loaded core, and held at most 2 247 in memory.
        #
        'queue.size="20000"',
        'queue.highWatermark="2000"',
        'queue.lowWatermark="1000"',
        f'queue.maxDiskSpace="{target.disk_mib}m"',
        'queue.saveOnShutdown="on"',
        #
        # Not optional. A full queue otherwise makes rsyslog wait to enqueue,
        # and everything behind it waits too: with the default, the node's own
        # day file got 7 145 of 59 998 records while one receiver's queue was
        # full (measured 26-10-12). With 0 the line is dropped for this
        # receiver alone, and counted as `discarded.full`.
        #
        'queue.timeoutEnqueue="0"',
        'action.resumeRetryCount="-1"',
        'action.resumeInterval="10"',
    ]
    first, *rest = parameters
    return [
        f"    action({first}",
        *(f"           {item}" for item in rest[:-1]),
        f"           {rest[-1]})",
    ]


def render(targets: Sequence[LogTarget], *, traffic_logging: bool) -> dict[str, str]:
    """`managed/rsyslog/`, and `rsyslog/` on the node. Empty when nothing is sent anywhere."""

    if not targets:
        return {}
    lines = [
        *HEADER,
        "",
        #
        # The record as RFC 5424, with the node's host name and HAProxy's tag
        # in the header, as the ring sent it. `%msg` from the second character:
        # the local socket keeps RFC 3164's space between the tag and the
        # record (the day file's template skips it the same way).
        #
        f'template(name="{TEMPLATE}" type="string"',
        '         string="<%PRI%>1 %TIMESTAMP:::date-rfc3339% %HOSTNAME% %APP-NAME% %PROCID% - - '
        '%msg:2:$:drop-last-lf%")',
        "",
        #
        # The structured records only, as the day file takes them: a line on
        # this tag that is not JSON is a duplicate of the classic log's.
        #
        'if ($programname == "haproxy-traffic" and $msg startswith " {") then {',
    ]
    for target in sorted(targets, key=lambda item: item.name):
        lines += _action(target)
    if not traffic_logging:
        #
        # No day file on this cluster: without a stop here the line would go
        # on to Ubuntu's 49-haproxy.conf and into the classic log. With the
        # traffic log on, 48-haprion-traffic.conf writes it and stops it.
        #
        lines.append("    stop")
    lines.append("}")
    return {FILE: "\n".join(lines) + "\n"}
