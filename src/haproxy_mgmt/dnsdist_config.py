"""DNS objects in, dnsdist configuration out (Fas 19, B249).

Community HAProxy 3.4 cannot listen on UDP outside `log-forward`, so a `dns`
object is served by dnsdist instead, on the same nodes and the same VIPs. This
module is to dnsdist what `generate` is to HAProxy: the only place that writes
its language. `generate` decides which objects are dns, places them on their
VIPs and refuses collisions with everything else the cluster binds; this
module turns the placed objects into one file.

**One file for the cluster.** dnsdist reads one configuration, so every dns
object of a cluster is a section of the same `dnsdist.conf`: a listener per
address and port, a pool per object, and per object a rule refusing who may
not ask - when `allow_from` names anyone - and one sending the rest to the
pool. A final rule refuses whatever reached a
listener without matching one, so nothing is answered by a pool nobody named.

**Counted per object under the pool's name** (B250's "used by metrics"). Rules
carry names, and dnsdist reports each rule's hits under it: `<pool>` matches
every query reaching the object's listener and does nothing else
(`NoneAction`, so the rules after it still decide), `<pool>/tcp` the ones over
TCP, `<pool>/refused` the ones refused for `allow_from`. Servers are named
`<pool>/s<n>`, so their counters say which pool they serve; `/` is outside the
model's name pattern and splits the two without guessing. Measured on dnsdist
2.1.2, 26-10-06: a named `NoneAction` counts and lets the next rule act, and a
rule without a name gets a fresh UUID at every start.

**What every pool does, whatever the object says.** EDNS Client Subnet carries
the asking client's address to the servers behind (`useClientSubnet`, the
full address). A Pi-hole needs it to tell its clients apart: its rate limit is
per client, and without the subnet every client behind the listener would be
one (FTL's own documentation; the lab showed Pi-hole logging the real client,
26-10-06). Statistics are served on loopback without a key, for the node's
status to read; the API stays closed, and no console is configured.

**A server may be named** (B252, 26-10-06). dnsdist takes addresses only and
looks nothing up, so the name is looked up when the object is saved, with the
manager's resolver, and the address is stored in the object beside it
(`with_addresses`, B261, 26-10-08); the address is written here with the name
beside it as a comment. Looked up then and not on the node: a node that needed
DNS to start dnsdist would need the servers dnsdist stands in front of. Not at
publishing either, since B261: a publish of something else - a log target, a
neighbouring object - re-resolved every name, so it could move a dns server
nobody touched, and a resolver that failed refused a publish that was not about
DNS at all. The cost is that the address is the one the name had at saving;
`status_collect` says when the name has moved since, and saving the object
again (*Look up again*) looks it up anew.

The output is Lua, and every value written into it has been held to a pattern
by the model or comes from the cluster's own configuration: addresses parse as
addresses, names match the model's name pattern, numbers are numbers. Nothing a
person typed reaches the file as text.
"""

from __future__ import annotations

import ipaddress
import socket
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass

from haproxy_mgmt.config import Vip
from haproxy_mgmt.proxy_model import (
    HOSTNAME,
    Backend,
    Health,
    Proxy,
    dump_document,
    duration_ms,
    is_range,
    read_document,
)

FILE = "dnsdist.conf"
#
# Where the node's status reads the counters, beside the WAF engine's 9520.
# Loopback only, unless the cluster runs HAProxy's Prometheus exporter: then
# on every IPv4 address as the exporter is, for its sources (B253), so the
# same scraper reads dnsdist at <node>:9521/metrics. The generator refuses
# anything else on the port either way.
#
STATS_PORT = 9521
HEADER = (
    "-- Generated by Haprion. Do not edit.",
    "--",
    "-- This file is rewritten in full every time the dns objects it comes from",
    "-- are published, and dnsdist is restarted with it when it changed.",
)


@dataclass(frozen=True, slots=True)
class DnsLayer:
    files: dict[str, str]
    """`managed/dns/`, and `dns/` on the node. Empty when no object is dns."""

    parts: dict[str, dict[str, str]]
    """Per object, the release manifest's four parts (see `object_manifest`)."""


def pool_name(proxy: Proxy) -> str:
    """The pool's name, as HAProxy names an object's backend (B250): the pool's own.

    Unique in the cluster by the generator's rule, which holds for dns objects
    too - two pools of one name would be one pool to dnsdist.
    """

    return proxy.backend or ""


class Unresolved(ValueError):
    """A server's name that does not give exactly one address to write."""


type Lookup = Callable[[str], str]


def is_address(host: str) -> bool:
    try:
        ipaddress.ip_address(host.strip("[]"))
    except ValueError:
        return False
    return True


def lookup(host: str) -> str:
    """The one address a server's name stands for, by the resolver of this host.

    IPv4 first, as the servers behind a resolver are usually reached; IPv6 when
    the name has only that. A name with no address, or with several of one
    family, is refused: dnsdist forwards to one address per server, and picking
    one of several would be a guess that changes with the order of an answer.
    """

    try:
        found = socket.getaddrinfo(host, None, type=socket.SOCK_DGRAM)
    except (socket.gaierror, UnicodeError) as exc:
        raise Unresolved(f"{host} does not resolve on the manager ({exc})") from exc
    addresses = sorted({str(entry[4][0]) for entry in found})
    for version in (4, 6):
        family = [
            address for address in addresses if ipaddress.ip_address(address).version == version
        ]
        if len(family) == 1:
            return family[0]
        if len(family) > 1:
            raise Unresolved(
                f"{host} resolves to several addresses ({', '.join(family)}); "
                f"write the one dnsdist should use"
            )
    raise Unresolved(f"{host} has no address on the manager")


def with_addresses(name: str, document: str, resolve: Lookup = lookup) -> str:
    """The object with each dns server name's address stored beside it (B261).

    What the interface does when a dns object is saved, and the one place a
    name is looked up for one: publishing reads the stored address and looks
    nothing up. Every name is looked up again, so saving is also how an
    address that moved is followed. An object that is not a dns object, or a
    server given as an address, is returned with no address beside it. A name
    that gives no single address refuses, as `lookup` says why.
    """

    data = read_document(name, document.encode("utf-8"))
    listen = data.get("listen")
    backends = data.get("backends")
    is_dns = isinstance(listen, Mapping) and listen.get("protocol") == "dns"
    if not isinstance(backends, Mapping):
        return document
    for pool in backends.values():
        servers = pool.get("servers") if isinstance(pool, Mapping) else None
        for server in servers if isinstance(servers, list) else ():
            if not isinstance(server, dict):
                continue
            host = server.get("host")
            server.pop("address", None)
            if is_dns and isinstance(host, str) and host and not is_address(host):
                server["address"] = resolve(host)
    return dump_document(data)


def server_name(index: int) -> str:
    """The position, not the address: what `generate` calls a pool member too."""

    return f"s{index + 1}"


#
# What separates a pool's name from what is counted of it, in a rule's or a
# server's name. Not in `proxy_model.NAME`, so the first one splits exactly.
#
COUNTED = "/"
TCP_RULE = "tcp"
REFUSED_RULE = "refused"


def counted_name(pool: str, part: str) -> str:
    """`<pool>/<part>`: a server's name, or a counting rule's."""

    return f"{pool}{COUNTED}{part}"


def _quote(value: str) -> str:
    """A Lua string. The values reaching here hold no quote or backslash."""

    if '"' in value or "\\" in value or "\n" in value:
        raise ValueError(f"refusing to write {value!r} into dnsdist configuration")
    return f'"{value}"'


def _endpoint(address: str, port: int) -> str:
    parsed = ipaddress.ip_address(address.strip("[]"))
    return f"[{parsed}]:{port}" if parsed.version == 6 else f"{parsed}:{port}"


def _host_mask(address: str) -> str:
    parsed = ipaddress.ip_address(address.strip("[]"))
    return f"{parsed}/{parsed.max_prefixlen}"


def _cidrs(entries: Sequence[str], networks: Mapping[str, Sequence[str]]) -> list[str]:
    """Group names resolved to the cluster's ranges, literal ranges kept."""

    return sorted(
        {cidr for entry in entries for cidr in ((entry,) if is_range(entry) else networks[entry])}
    )


def _check(health: Health) -> str:
    if health.type == "disabled":
        #
        # Always up: a pool nobody checks is a decision, and dnsdist's word
        # for it. Without it dnsdist would check anyway, with its defaults.
        #
        return 'healthCheckMode="up"'
    return (
        f"checkName={_quote(health.query_name or '.')}, "
        f"checkType={_quote(health.query_type or 'A')}, "
        f"checkInterval={duration_ms(health.interval) // 1000}, "
        f"rise={health.rise}, maxCheckFailures={health.fall}"
    )


def _servers(proxy: Proxy, pool: Backend, source: str | None) -> list[str]:
    lines = []
    for index, server in enumerate(pool.servers):
        named = not is_address(server.host)
        if named and not HOSTNAME.match(server.host):
            raise ValueError(f"refusing to write {server.host!r} into dnsdist configuration")
        address = server.address if named else server.host
        if address is None:
            raise Unresolved(
                f"{proxy.name}: {server.host} has no address saved with it; save the object "
                f"again so the manager looks the name up"
            )
        fields = [
            f"address={_quote(_endpoint(address, server.port))}",
            f"name={_quote(counted_name(pool_name(proxy), server_name(index)))}",
            f"pool={_quote(pool_name(proxy))}",
            "useClientSubnet=true",
        ]
        if source is not None:
            fields.append(f"source={_quote(str(ipaddress.ip_address(source)))}")
        fields.append(_check(pool.health))
        line = f"newServer({{{', '.join(fields)}}})"
        #
        # The name it was looked up from, for a reader and for the status's
        # comparison (`status_collect.dns_servers_moved`). Held to the model's
        # hostname pattern, so nothing in it can end the comment early.
        #
        lines.append(f"{line} -- {NAMED}{server.host}" if named else line)
    return lines


def _match(vip: Vip, port: int) -> str:
    return f"NetmaskGroupRule({_quote(_host_mask(vip.address))}, false), DSTPortRule({port})"


def _rules(proxy: Proxy, vip: Vip, networks: Mapping[str, Sequence[str]]) -> list[str]:
    port = proxy.listen.port
    if port is None:
        raise ValueError(f"{proxy.name} is a dns object without a port")
    pool = pool_name(proxy)
    match = _match(vip, port)
    counting = [
        f"addAction(AndRule({{{match}}}), NoneAction(), {{name={_quote(pool)}}})",
        f"addAction(AndRule({{{match}, TCPRule(true)}}), NoneAction(), "
        f"{{name={_quote(counted_name(pool, TCP_RULE))}}})",
    ]
    route = f"addAction(AndRule({{{match}}}), PoolAction({_quote(pool)}))"
    if not proxy.allow_from:
        return [*counting, route]
    allowed = ", ".join(_quote(cidr) for cidr in _cidrs(proxy.allow_from, networks))
    return [
        *counting,
        f"addAction(AndRule({{{match}, NotRule(NetmaskGroupRule({{{allowed}}}))}}), "
        f"RCodeAction(DNSRCode.REFUSED), {{name={_quote(counted_name(pool, REFUSED_RULE))}}})",
        route,
    ]


def _webserver(scrapers: Sequence[str]) -> list[str]:
    """dnsdist's statistics: the node's status on loopback, and the exporter's scrapers.

    One ACL for every address the web server listens on (2.1's
    `setWebserverConfig`), so loopback stays in it when the scrapers join. The
    statistics need no key, as on loopback; the API keeps requiring one, and no
    key is configured, so it stays shut.
    """

    allowed = [
        "127.0.0.1/32",
        *(str(ipaddress.ip_network(entry, strict=False)) for entry in scrapers),
    ]
    listen = f"0.0.0.0:{STATS_PORT}" if scrapers else f"127.0.0.1:{STATS_PORT}"
    return [
        f"webserver({_quote(listen)})",
        f"setWebserverConfig({{acl={_quote(', '.join(dict.fromkeys(allowed)))}, "
        "statsRequireAuthentication=false, apiRequiresAuthentication=true})",
    ]


#
# What precedes a looked-up server's name in its comment.
#
NAMED = "looked up from "


def render(
    placed: Sequence[tuple[Vip, Proxy, str | None]],
    networks: Mapping[str, Sequence[str]],
    scrapers: Sequence[str] = (),
) -> DnsLayer:
    """The cluster's dnsdist configuration, from its dns objects and where they sit.

    `placed` is (VIP, object, source address) per dns object, in name order,
    as `generate` decided them. Empty gives no file at all - the release then
    carries no `dns/`, which is what stops dnsdist on the nodes.

    `scrapers` are the sources of the cluster's Prometheus exporter, and empty
    when it has none: with them, the statistics are served on every address for
    them as well as for the node itself.
    """

    if not placed:
        return DnsLayer(files={}, parts={})
    listeners: list[str] = []
    for vip, proxy, _source in placed:
        port = proxy.listen.port
        if port is None:
            raise ValueError(f"{proxy.name} is a dns object without a port")
        endpoint = _endpoint(vip.address, port)
        if endpoint not in listeners:
            listeners.append(endpoint)

    parts: dict[str, dict[str, str]] = {}
    pools: list[str] = []
    rules: list[str] = []
    for vip, proxy, source in placed:
        pool = proxy.backends[proxy.backend or ""]
        servers = _servers(proxy, pool, source)
        policy = f"setPoolServerPolicy({pool.balance}, {_quote(pool_name(proxy))})"
        routing = _rules(proxy, vip, networks)
        pools += [f"-- {proxy.name}", *servers, policy, ""]
        rules += [f"-- {proxy.name}", *routing]
        port = proxy.listen.port or 0
        parts[proxy.name] = {
            "backends": "\n".join([*servers, policy]) + "\n",
            "routing": "\n".join(routing) + "\n",
            "listener": f"{_endpoint(vip.address, port)}\n",
            "certificate": "",
        }

    lines = [
        *HEADER,
        "",
        "-- No call to the outside world for security status; the package version is",
        "-- reported by the node and kept current like every other package.",
        'setSecurityPollSuffix("")',
        "",
        "-- Who may ask is each object's allow_from, refused by the rules below; the",
        "-- global list admits all and decides nothing.",
        'setACL({"0.0.0.0/0", "::/0"})',
        "",
        "-- The asking client's full address travels to the servers (EDNS Client Subnet).",
        "setECSSourcePrefixV4(32)",
        "setECSSourcePrefixV6(128)",
        "setECSOverride(true)",
        "",
        f"setLocal({_quote(listeners[0])})",
        *(f"addLocal({_quote(endpoint)})" for endpoint in listeners[1:]),
        "",
        *pools,
        *rules,
        "",
        "-- Whatever reached a listener without matching an object is refused.",
        "addAction(AllRule(), RCodeAction(DNSRCode.REFUSED))",
        "",
        *_webserver(scrapers),
        "",
    ]
    return DnsLayer(files={FILE: "\n".join(lines)}, parts=parts)
