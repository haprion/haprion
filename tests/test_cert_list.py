SCHEMA_DIR = Path(__file__).resolve().parents[1] / "schemas" / "v1"
SCHEMA_ID = "https://example.com/haprion/schemas/v1/haprion-cert-list.schema.json"


def _validator() -> Draft202012Validator:
    registry = Registry()
    schema: dict[str, object] = {}
    for path in sorted(SCHEMA_DIR.glob("*.schema.json")):
        loaded = json.loads(path.read_text(encoding="utf-8"))
        registry = registry.with_resource(str(loaded["$id"]), Resource.from_contents(loaded))
        if loaded["$id"] == SCHEMA_ID:
            schema = loaded
    return Draft202012Validator(schema, registry=registry, format_checker=FormatChecker())


def _pem(common_name: str, *, sans: tuple[str, ...] = (), days: int = 30) -> str:
    """A self-signed key-plus-leaf file, shaped like the published ones."""

    completed = subprocess.run(
        [
            "/usr/bin/openssl",
            "req",
            "-x509",
            "-newkey",
            "rsa:2048",
            "-keyout",
            "-",
            "-out",
            "-",
            "-days",
            str(days),
            "-nodes",
            "-subj",
            f"/CN={common_name}",
            *(
                ("-addext", "subjectAltName=" + ",".join(f"DNS:{name}" for name in sans))
                if sans
                else ()
            ),
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    return completed.stdout


def _cluster(ids: tuple[str, ...]) -> Any:
    return type("Cluster", (), {"certificate_ids": ids})


class LeafOnlyTests(unittest.TestCase):
    def test_the_private_key_never_reaches_the_parser(self) -> None:
        #
        # The published file is key plus chain. What is handed to openssl is the
        # leaf block alone, so "the key does not leave the helper" is a property
        # of what is passed rather than a rule someone has to follow.
        #
        from haprion.certificates import leaf_block

        block = leaf_block(_pem("example.test"))

        self.assertNotIn("PRIVATE", block)
        self.assertTrue(block.startswith(f"{'-' * 5}BEGIN CERTIFICATE{'-' * 5}"))
        self.assertEqual(block.count("BEGIN CERTIFICATE"), 1)


class DescribeTests(unittest.TestCase):
    def test_subject_sans_issuer_and_validity_are_read_from_the_certificate(self) -> None:
        from haprion.certificates import leaf_block

        facts = cert_inventory.describe(
            leaf_block(_pem("example.test", sans=("example.test", "www.example.test")))
        )

        self.assertEqual(facts.common_name, "example.test")
        self.assertEqual(facts.sans, ("example.test", "www.example.test"))
        self.assertIn("example.test", facts.issuer)
        self.assertLess(facts.not_before, facts.not_after)

    def test_something_that_is_not_a_certificate_is_refused(self) -> None:
        from haprion.certificates import CertificateError

        edge = "-" * 5
        with self.assertRaises(CertificateError):
            cert_inventory.describe(
                f"{edge}BEGIN CERTIFICATE{edge}\nnope\n{edge}END CERTIFICATE{edge}\n"
            )


class LifecycleTests(unittest.TestCase):
    def test_a_certificate_certbot_has_issued_is_acme(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory) / "certdist"
            root.mkdir()
            renewed = _pem("renewed.test")
            (root / "renewed.pem").write_text(renewed, encoding="ascii")
            (root / "manual.pem").write_text(_pem("manual.test"), encoding="ascii")

            letsencrypt = Path(directory) / "letsencrypt"
            (letsencrypt / "archive" / "renewed.test").mkdir(parents=True)
            (letsencrypt / "archive" / "renewed.test" / "cert1.pem").write_text(
                renewed, encoding="ascii"
            )

            result = cert_inventory.cert_list_result(
                root, _cluster(("renewed",)), letsencrypt_root=letsencrypt
            )

        by_id = {entry["id"]: entry for entry in result["certificates"]}
        self.assertEqual(by_id["renewed"]["lifecycle"], "acme")
        self.assertEqual(by_id["manual"]["lifecycle"], "static")

    def test_the_previous_certificate_of_a_lineage_still_counts_as_renewed(self) -> None:
        #
        # A renewal writes the new certificate before the deploy hook publishes
        # it. During that window the distributed copy is the lineage's previous
        # certificate, and matching only against the live one would report
        # "nothing renews this" about a certificate that had just been renewed.
        #
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory) / "certdist"
            root.mkdir()
            previous = _pem("rolling.test")
            current = _pem("rolling.test")
            (root / "rolling.pem").write_text(previous, encoding="ascii")

            letsencrypt = Path(directory) / "letsencrypt"
            archive = letsencrypt / "archive" / "rolling.test"
            archive.mkdir(parents=True)
            (archive / "cert1.pem").write_text(previous, encoding="ascii")
            (archive / "cert2.pem").write_text(current, encoding="ascii")
            live = letsencrypt / "live" / "rolling.test"
            live.mkdir(parents=True)
            (live / "cert.pem").write_text(current, encoding="ascii")

            renewed = cert_inventory.renewed_fingerprints(letsencrypt)

        self.assertIn(leaf_fingerprint(previous), renewed)
        self.assertIn(leaf_fingerprint(current), renewed)

    def test_a_damaged_lineage_file_does_not_break_the_listing(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            letsencrypt = Path(directory)
            archive = letsencrypt / "archive" / "broken.test"
            archive.mkdir(parents=True)
            (archive / "cert1.pem").write_text("not a certificate", encoding="ascii")

            self.assertEqual(cert_inventory.renewed_fingerprints(letsencrypt), frozenset())


class ResultTests(unittest.TestCase):
    def _result(self, directory: str, ids: tuple[str, ...], **kwargs: Any) -> dict[str, Any]:
        root = Path(directory)
        return cert_inventory.cert_list_result(
            root, _cluster(ids), letsencrypt_root=Path(directory) / "none", **kwargs
        )

    def test_referenced_certificates_come_first_in_configured_order(self) -> None:
        #
        # The unreferenced ones are listed too: they are what could be chosen
        # next, and a picker that could only see what is already configured
        # would be no picker.
        #
        with tempfile.TemporaryDirectory() as directory:
            for name in ("alpha", "bravo", "charlie"):
                (Path(directory) / f"{name}.pem").write_text(_pem(f"{name}.test"), encoding="ascii")
            result = self._result(directory, ("charlie", "alpha"))

        self.assertEqual(
            [entry["id"] for entry in result["certificates"]], ["charlie", "alpha", "bravo"]
        )
        self.assertEqual(
            [entry["referenced_by_cluster"] for entry in result["certificates"]],
            [True, True, False],
        )

    def test_the_registry_says_where_a_certificate_comes_from_and_goes(self) -> None:
        """With a registry (B135) every entry it names carries source and targets.

        A file the registry does not name is still listed, with both null:
        that is what a certificate published before the registry existed
        looks like, and hiding it would hide exactly the ones to register.
        """

        registry = config.Registry(
            receivers={
                "lb-01": config.Receiver(receiver_id="lb-01", path=Path("/x"), owner="svc-app")
            },
            certificates={
                "alpha": config.RegisteredCertificate(
                    certificate_id="alpha",
                    source=config.CertificateSource(kind="acme", lineage="alpha-wildcard"),
                    clusters=("alpha", "beta"),
                    receivers=("lb-01",),
                ),
            },
        )
        with tempfile.TemporaryDirectory() as directory:
            for name in ("alpha", "bravo"):
                (Path(directory) / f"{name}.pem").write_text(_pem(f"{name}.test"), encoding="ascii")
            result = self._result(directory, ("alpha",), registry=registry)
            document_result = cert_inventory.cert_list_result(
                Path(directory),
                _cluster(("alpha",)),
                letsencrypt_root=Path(directory) / "none",
                registry=registry,
            )

        by_id = {entry["id"]: entry for entry in result["certificates"]}
        self.assertEqual(by_id["alpha"]["source"], {"kind": "acme", "lineage": "alpha-wildcard"})
        self.assertEqual(
            by_id["alpha"]["targets"], {"clusters": ["alpha", "beta"], "receivers": ["lb-01"]}
        )
        self.assertIsNone(by_id["bravo"]["source"])
        self.assertIsNone(by_id["bravo"]["targets"])

        from haprion.envelope import envelope

        assert_contract(
            "haprion-cert-list",
            json.dumps(
                envelope(
                    operation="cert_list",
                    outcome="done",
                    cluster="alpha",
                    request_id="aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa",
                    result=document_result,
                )
            ),
        )

    def test_a_referenced_certificate_that_is_missing_is_listed_as_unusable(self) -> None:
        #
        # This is the case the listing is most needed for: cert-deploy refuses
        # the whole cluster for it, and the operator should learn it here rather
        # than from a refused rollout.
        #
        with tempfile.TemporaryDirectory() as directory:
            result = self._result(directory, ("absent",))

        entry = result["certificates"][0]
        self.assertFalse(entry["deployable"])
        self.assertIn("not present", entry["validation_error"])

    def test_a_file_that_is_not_a_certificate_is_listed_with_the_reason(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            (Path(directory) / "junk.pem").write_text("hello", encoding="ascii")
            result = self._result(directory, ())

        entry = result["certificates"][0]
        self.assertFalse(entry["deployable"])
        self.assertIsNotNone(entry["validation_error"])

    def test_an_expired_certificate_is_deployable_but_not_valid(self) -> None:
        #
        # Two different questions. An expired certificate can still be pushed -
        # that is how a node is repaired after one was deployed too late - so
        # expiry belongs in `valid`, not in `deployable`.
        #
        with tempfile.TemporaryDirectory() as directory:
            (Path(directory) / "old.pem").write_text(_pem("old.test", days=1), encoding="ascii")
            result = self._result(directory, ("old",), now=datetime.now(UTC) + timedelta(days=400))

        entry = result["certificates"][0]
        self.assertTrue(entry["deployable"])
        self.assertFalse(entry["valid"])


class RegistryListingTests(unittest.TestCase):
    """The central listing (C5): every certificate the manager holds, not one cluster's.

    The per-cluster listing reads the distribution directory, so a certificate
    that goes only to receivers is absent from it entirely. These cover the
    other half - measured at the source, which is what a renewal writes first.
    """

    def _registry(self, root: Path, **kwargs: Any) -> config.Registry:
        receivers = {
            name: config.Receiver(receiver_id=name, path=root / "receivers" / name, owner="svc-app")
            for name in kwargs.pop("receiver_names", ())
        }
        return config.Registry(receivers=receivers, certificates=kwargs["certificates"])

    def _entry(
        self,
        identifier: str,
        *,
        kind: str = "acme",
        lineage: str | None = None,
        clusters: tuple[str, ...] = (),
        receivers: tuple[str, ...] = (),
    ) -> config.RegisteredCertificate:
        return config.RegisteredCertificate(
            certificate_id=identifier,
            source=config.CertificateSource(kind=kind, lineage=lineage),
            clusters=clusters,
            receivers=receivers,
        )

    def _run(
        self, root: Path, registry: config.Registry, now: datetime | None = None
    ) -> dict[str, Any]:
        return cert_inventory.registry_result(
            registry,
            certificate_root=root / "certdist",
            renewed=frozenset(),
            now=now or datetime.now(UTC),
            live=root / "live",
            store=root / "import",
        )

    def test_a_receiver_only_certificate_is_measured_at_its_source(self) -> None:
        #
        # The case the per-cluster listing cannot answer at all: nothing for
        # this certificate exists in the distribution directory, so its subject,
        # SAN and expiry can only come from where certbot writes it.
        #
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = root / "live" / "lb-01-lineage"
            source.mkdir(parents=True)
            (source / "fullchain.pem").write_text(
                _pem("lb-01.example.net", sans=("lb-01.example.net",)), encoding="ascii"
            )
            registry = self._registry(
                root,
                receiver_names=("lb-01",),
                certificates={
                    "lb-01.example.net": self._entry(
                        "lb-01.example.net", lineage="lb-01-lineage", receivers=("lb-01",)
                    )
                },
            )
            result = self._run(root, registry)

        entry = result["certificates"][0]
        self.assertTrue(entry["readable"])
        self.assertEqual(entry["common_name"], "lb-01.example.net")
        self.assertEqual(entry["sans"], ["lb-01.example.net"])
        self.assertEqual(result["receivers"], ["lb-01"])
        #
        # No clusters, so there is no shared distribution copy to report on -
        # null rather than a made-up "not published", which would read as a
        # problem rather than as an inapplicable question.
        #
        self.assertIsNone(entry["distribution"])

    def test_a_receiver_says_when_it_was_published_and_never_whether_it_arrived(self) -> None:
        """`published_at` is the manager's own write, and there is no third field.

        What the receiver did with the file is unknowable here by design: it
        pulls on its own schedule with its own key and reports nothing back.
        A field claiming arrival would be the interface's most confident lie.
        """

        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = root / "live" / "lineage"
            source.mkdir(parents=True)
            material = _pem("one.example.net")
            (source / "fullchain.pem").write_text(material, encoding="ascii")

            published = root / "receivers" / "current" / "one"
            published.mkdir(parents=True)
            (published / "fullchain.pem").write_text(material, encoding="ascii")

            stale = root / "receivers" / "stale" / "one"
            stale.mkdir(parents=True)
            (stale / "fullchain.pem").write_text(_pem("one.example.net"), encoding="ascii")

            registry = self._registry(
                root,
                receiver_names=("current", "stale", "never"),
                certificates={
                    "one": self._entry(
                        "one", lineage="lineage", receivers=("current", "stale", "never")
                    )
                },
            )
            result = self._run(root, registry)

        by_id = {r["id"]: r for r in result["certificates"][0]["targets"]["receivers"]}
        self.assertEqual(set(by_id), {"current", "stale", "never"})
        self.assertTrue(by_id["current"]["current"])
        self.assertIsNotNone(by_id["current"]["published_at"])
        self.assertFalse(by_id["stale"]["current"])
        self.assertIsNone(by_id["never"]["published_at"])
        self.assertEqual(set(by_id["current"]), {"id", "format", "published_at", "current"})

    def test_an_unreadable_source_leaves_current_unknown_rather_than_false(self) -> None:
        #
        # An out-of-date target and a target nothing could be compared against
        # are different facts. Reporting the second as the first would send an
        # operator to republish a certificate that is already correct.
        #
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            published = root / "receivers" / "lb-01"
            published.mkdir(parents=True)
            (published / "fullchain.pem").write_text(_pem("one.example.net"), encoding="ascii")
            registry = self._registry(
                root,
                receiver_names=("lb-01",),
                certificates={"one": self._entry("one", lineage="absent", receivers=("lb-01",))},
            )
            result = self._run(root, registry)

        entry = result["certificates"][0]
        self.assertFalse(entry["readable"])
        self.assertIsNone(entry["targets"]["receivers"][0]["current"])

    def test_an_import_with_nothing_anywhere_is_listed_with_the_reason(self) -> None:
        #
        # What an imported certificate looks like until C6 builds the import
        # store, when nothing has been published for it either. The publisher
        # calls it skipped, so the listing says the same rather than calling
        # it broken.
        #
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            registry = self._registry(
                root,
                certificates={
                    "internal": self._entry("internal", kind="import", clusters=("beta",))
                },
            )
            result = self._run(root, registry)

        entry = result["certificates"][0]
        self.assertFalse(entry["readable"])
        self.assertIn("no material at its source", entry["validation_error"])
        self.assertIsNone(entry["fingerprint_sha256"])
        self.assertIsNone(entry["measured_at"])
        self.assertNotIn("request_state", entry)

    def test_an_import_the_ca_is_still_holding_says_pending(self) -> None:
        #
        # C6: the same empty import, but a request for it is on the disk and
        # has no certificate yet. Said as its own field, so the interface can
        # tell waiting from broken without parsing the sentence.
        #
        from haprion.ndes_state import request_directory

        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            requests = root / "requests"
            pending = request_directory(requests, "internal")
            pending.mkdir(parents=True)
            (pending / "request.json").write_text('{"certificate": "internal"}')
            registry = self._registry(
                root,
                certificates={
                    "internal": self._entry("internal", kind="import", clusters=("beta",)),
                    "other": self._entry("other", kind="import", clusters=("beta",)),
                },
            )
            result = cert_inventory.registry_result(
                registry,
                certificate_root=root / "certdist",
                renewed=frozenset(),
                now=datetime.now(UTC),
                live=root / "live",
                store=root / "import",
                request_root=requests,
            )
            by_id = {entry["id"]: entry for entry in result["certificates"]}
            self.assertEqual(by_id["internal"]["request_state"], "pending")
            self.assertNotIn("request_state", by_id["other"])
            # Once the CA has answered, the material is beside the record and
            # the request is no longer pending, whatever the import says.
            (pending / "cert.pem").write_text("not yet imported")
            result = cert_inventory.registry_result(
                registry,
                certificate_root=root / "certdist",
                renewed=frozenset(),
                now=datetime.now(UTC),
                live=root / "live",
                store=root / "import",
                request_root=requests,
            )
            self.assertNotIn("request_state", result["certificates"][0])

    def test_a_request_the_ca_is_holding_is_listed_without_a_registry_entry(self) -> None:
        #
        # Review 2026-09-17, finding 1: a request the CA holds is not in the
        # registry any more - an entry without material refused every rollout
        # to its clusters - so the listing reads the request itself, with the
        # targets kept beside it, and shows it in the row shape the interface
        # already knows. The frozen schema must take the row.
        #
        from haprion.envelope import envelope
        from haprion.ndes_state import request_directory, write_targets

        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            requests = root / "requests"
            pending = request_directory(requests, "waiting.example")
            pending.mkdir(parents=True)
            (pending / "request.json").write_text(
                json.dumps(
                    {
                        "certificate": "waiting.example",
                        "profile": "certserver1",
                        "domains": ["waiting.example", "*.waiting.example"],
                    }
                )
            )
            write_targets(requests, "waiting.example", clusters=("beta",), receivers=("lb-01",))
            # Noise the listing must not turn into rows: a directory whose
            # record names another ID, and one the CA has answered.
            stray = requests / ("0" * 24)
            stray.mkdir()
            (stray / "request.json").write_text('{"certificate": "waiting.example"}')
            answered = request_directory(requests, "done.example")
            answered.mkdir()
            (answered / "request.json").write_text('{"certificate": "done.example"}')
            (answered / "cert.pem").write_text("issued")
            registry = self._registry(
                root,
                receiver_names=("lb-01",),
                certificates={"other": self._entry("other", kind="import", clusters=("beta",))},
            )
            result = cert_inventory.registry_result(
                registry,
                certificate_root=root / "certdist",
                renewed=frozenset(),
                now=datetime.now(UTC),
                live=root / "live",
                store=root / "import",
                request_root=requests,
            )
            by_id = {entry["id"]: entry for entry in result["certificates"]}
            self.assertEqual(set(by_id), {"other", "waiting.example"})
            row = by_id["waiting.example"]
            self.assertEqual(row["request_state"], "pending")
            self.assertFalse(row["readable"])
            self.assertEqual(
                row["source"], {"kind": "import", "lineage": None, "ndes_profile": "certserver1"}
            )
            self.assertEqual(row["targets"]["clusters"], ["beta"])
            self.assertEqual(
                row["targets"]["receivers"],
                [{"id": "lb-01", "format": "pem", "published_at": None, "current": None}],
            )
            self.assertIsNone(row["distribution"])
            _validator().validate(
                envelope(
                    operation="cert_list",
                    outcome="done",
                    cluster="alpha",
                    request_id="aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa",
                    result={"certificates": [], "registry": result},
                )
            )

