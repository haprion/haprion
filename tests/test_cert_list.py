class RegistryCommandTests(unittest.TestCase):
    """`haprion-cert-list -c <cluster> --registry`, the CLI half of the C5 view.

    The parity rule: the interface must not be able to show something the
    command line cannot. `-c` is still required because the registry travels in
    the cluster listing's answer rather than in a helper of its own.
    """

    def _document(self, registry: dict[str, Any] | None) -> dict[str, Any]:
        result: dict[str, Any] = {"certificates": []}
        if registry is not None:
            result["registry"] = registry
        return {
            "schema_version": 1,
            "ok": True,
            "outcome": "done",
            "operation": "cert_list",
            "cluster": "alpha",
            "request_id": "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa",
            "result": result,
            "warnings": [],
            "error": None,
        }

    def _entry(self, **overrides: object) -> dict[str, Any]:
        entry: dict[str, Any] = {
            "id": "example.com",
            "source": {"kind": "acme", "lineage": "example.com-wildcard"},
            "targets": {"clusters": ["alpha"], "receivers": []},
            "distribution": {"published_at": "2026-08-01T00:00:00Z", "current": True},
            "readable": True,
            "validation_error": None,
            "fingerprint_sha256": "c" * 64,
            "common_name": "*.example.com",
            "sans": ["*.example.com"],
            "not_before": "2026-08-01T00:00:00Z",
            "not_after": "2099-11-01T00:00:00Z",
            "issuer": "CN=Test CA",
            "lifecycle": "acme",
            "valid": True,
        }
        entry.update(overrides)
        return entry

    def _run(self, argv: list[str], document: dict[str, Any]) -> tuple[str, str, int]:
        out, err = io.StringIO(), io.StringIO()

        def run_helper(cluster: str, request_id: str) -> Any:
            return type(
                "Completed", (), {"stdout": json.dumps(document), "stderr": "", "returncode": 0}
            )

        code = cert_list.main(argv, stream_out=out, stream_err=err, run_helper=run_helper)
        return out.getvalue(), err.getvalue(), code

    def test_it_lists_every_registered_certificate_and_where_each_goes(self) -> None:
        document = self._document(
            {
                "certificates": [
                    self._entry(),
                    self._entry(
                        id="lb-01.example.net",
                        targets={
                            "clusters": [],
                            "receivers": [
                                {
                                    "id": "lb-01",
                                    "published_at": "2026-08-01T00:00:00Z",
                                    "current": True,
                                }
                            ],
                        },
                        distribution=None,
                    ),
                ],
                "receivers": ["lb-01"],
            }
        )
        rendered, _, code = self._run(["-c", "alpha", "--registry"], document)

        self.assertEqual(code, 0)
        self.assertIn("example.com", rendered)
        self.assertIn("lb-01 (receiver)", rendered)
        #
        # The receiver-only certificate is the one the per-cluster listing
        # cannot show at all, so its presence here is the point of the mode.
        #
        self.assertIn("lb-01.example.net", rendered)

    def test_it_never_claims_a_receiver_installed_anything(self) -> None:
        document = self._document({"certificates": [self._entry()], "receivers": []})
        rendered, _, _ = self._run(["-c", "alpha", "--registry"], document)

        self.assertIn("reports nothing back", rendered)
        for claim in ("installed", "deployed", "arrived", "on all targets"):
            self.assertNotIn(claim, rendered.lower())

    def test_an_unreadable_certificate_says_why_instead_of_its_placeholders(self) -> None:
        #
        # Same rule as the per-cluster listing: the measured fields of an entry
        # that could not be read are inert, and printing them as measurements
        # would be the listing's worst possible failure.
        #
        document = self._document(
            {
                "certificates": [
                    self._entry(
                        readable=False,
                        validation_error="no material at its source yet",
                        fingerprint_sha256=None,
                        not_after="2026-08-01T00:00:00Z",
                        valid=False,
                    )
                ],
                "receivers": [],
            }
        )
        rendered, _, _ = self._run(["-c", "alpha", "--registry"], document)

        self.assertIn("UNREADABLE", rendered)
        self.assertIn("no material at its source yet", rendered)

    def test_an_installation_without_a_registry_says_so_rather_than_printing_nothing(self) -> None:
        _, errors, code = self._run(["-c", "alpha", "--registry"], self._document(None))

        self.assertNotEqual(code, 0)
        self.assertIn("certificate_registry", errors)

    def test_the_flags_may_be_given_in_either_order_and_not_twice(self) -> None:
        document = self._document({"certificates": [], "receivers": []})
        for argv in (
            ["-c", "alpha", "--registry", "--json"],
            ["-c", "alpha", "--json", "--registry"],
        ):
            rendered, _, code = self._run(argv, document)
            self.assertEqual(code, 0)
            self.assertIn('"registry"', rendered)

        with self.assertRaises(SystemExit):
            self._run(["-c", "alpha", "--registry", "--registry"], document)


class HelperTests(unittest.TestCase):
    """The privileged half, run end to end and held to its schema.

    Every other test in this file builds the envelope itself or stubs the
    helper out. That proves the result body and the schema agree; it cannot
    prove that the helper emits either, which is exactly the gap that let two
    other helpers answer off-contract for months.
    """

    def _run(self, *, cluster: str = "alpha", with_root: bool = True) -> tuple[int, str, str]:
        request = {
            "schema_version": 1,
            "operation": "cert_list",
            "cluster": cluster,
            "request_id": "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb",
            "parameters": {},
        }
        out, err = io.StringIO(), io.StringIO()

        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            (root / "example.com.pem").write_text(_pem("example.com"), encoding="utf-8")

            class Policy:
                certificate_root = root if with_root else None

            class Config:
                @staticmethod
                def cluster(cluster_id: str) -> object:
                    #
                    # Refuses an unknown cluster the way the real loader does.
                    # A fake that answers every question is a fake that cannot
                    # fail a test the real thing would fail.
                    #
                    if cluster_id != "alpha":
                        raise ConfigError(f"unknown cluster '{cluster_id}'", exit_code=64)
                    return _cluster(("example.com",))

                registry = None

            with (
                mock.patch.object(cert_list_helper, "load_policy", lambda *a, **k: Policy()),
                mock.patch.object(
                    cert_list_helper, "load_runtime_config", lambda *a, **k: Config()
                ),
            ):
                code = cert_list_helper.main(
                    [],
                    input_stream=io.BytesIO(json.dumps(request).encode("utf-8")),
                    output_stream=out,
                    error_stream=err,
                    require_root=False,
                )
        return code, out.getvalue(), err.getvalue()

    def test_a_listing_from_the_helper_matches_the_frozen_schema(self) -> None:
        code, out, err = self._run()

        self.assertEqual((code, err), (0, ""))
        document = assert_contract("haprion-cert-list", out)
        self.assertEqual(document["operation"], "cert_list")
        self.assertEqual(document["outcome"], "done")
        self.assertEqual(document["result"]["certificates"][0]["id"], "example.com")

    def test_an_unknown_cluster_is_refused_in_the_frozen_envelope(self) -> None:
        code, out, err = self._run(cluster="beta")

        self.assertEqual(code, 64)
        self.assertIn("unknown cluster", err)
        document = assert_contract("haprion-cert-list", out)
        self.assertEqual(document["outcome"], "failed")
        self.assertEqual(document["error"]["code"], "bad_input")
        self.assertIsNone(document["result"])

    def test_a_missing_certificate_root_is_a_structured_failure(self) -> None:
        code, out, _ = self._run(with_root=False)

        self.assertEqual(code, 65)
        document = assert_contract("haprion-cert-list", out)
        self.assertEqual(document["error"]["code"], "certificate_metadata_unavailable")


