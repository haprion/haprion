class Locking(Fixture):
    def test_a_run_waits_for_the_lock_and_gives_up_after_the_wait(self) -> None:
        issue(self.live / "example.com", "example.com")
        policy = self.write_config(
            {"example.com": {"source": {"kind": "acme"}, "clusters": ["alpha"]}}
        )
        handle = os.open(self.lock, os.O_RDWR | os.O_CREAT, 0o644)
        fcntl.flock(handle, fcntl.LOCK_EX)
        try:
            with (
                mock.patch.object(cert_publish, "LOCK_WAIT_SECONDS", 1),
                self.assertRaises(PublishError) as caught,
            ):
                self.run_publish(policy)
        finally:
            os.close(handle)
        self.assertEqual(caught.exception.code, "operation_locked")
        self.assertEqual(list(self.dist.iterdir()), [])

    def test_a_run_proceeds_once_the_other_lets_go(self) -> None:
        issue(self.live / "example.com", "example.com")
        policy = self.write_config(
            {"example.com": {"source": {"kind": "acme"}, "clusters": ["alpha"]}}
        )
        handle = os.open(self.lock, os.O_RDWR | os.O_CREAT, 0o644)
        fcntl.flock(handle, fcntl.LOCK_EX)
        released = threading.Timer(0.3, lambda: os.close(handle))
        released.start()

        report = self.run_publish(policy)

        released.join()
        self.assertEqual(report.certificates[0].status, "published")


class TheCommand(Fixture):
    def test_the_json_envelope_and_the_summary(self) -> None:
        issue(self.live / "example.com", "example.com")
        (self.dist / "lb.example.org.pem").write_bytes(b"by hand\n")
        policy = self.write_config(
            {
                "example.com": {"source": {"kind": "acme"}, "clusters": ["alpha"]},
                "lb.example.org": {"source": {"kind": "import"}, "clusters": ["alpha"]},
            }
        )

        code, out, _ = self.run_command(policy, "--json")

        self.assertEqual(code, 0)
        document = json.loads(out)
        self.assertEqual(document["operation"], "cert_publish")
        self.assertEqual(document["outcome"], "partial")
        self.assertIsNone(document["cluster"])
        self.assertEqual(document["warnings"][0]["code"], "source_missing")
        self.assertEqual(document["result"]["changed_clusters"], ["alpha"])
        by_id = {c["id"]: c for c in document["result"]["certificates"]}
        self.assertEqual(by_id["example.com"]["status"], "published")
        self.assertRegex(by_id["example.com"]["fingerprint_sha256"], r"^[0-9a-f]{64}$")
        self.assertEqual(by_id["lb.example.org"]["status"], "skipped")
        self.assertNotIn("PRIVATE", out)

        code, out, _ = self.run_command(policy)
        self.assertEqual(code, 0)
        self.assertIn("example.com: unchanged (cluster alpha)", out)
        self.assertIn("lb.example.org: skipped", out)

    def test_deploy_rolls_out_each_changed_cluster_once_after_publishing(self) -> None:
        issue(self.live / "example.com", "example.com")
        issue(self.live / "example.net", "example.net")
        policy = self.write_config(
            {
                "example.com": {"source": {"kind": "acme"}, "clusters": ["alpha", "beta"]},
                "example.net": {"source": {"kind": "acme"}, "clusters": ["alpha"]},
            }
        )
        seen: list[tuple[str, list[str]]] = []

        def deployer(cluster_id: str) -> int:
            seen.append((cluster_id, sorted(p.name for p in self.dist.iterdir())))
            return 0

        code, out, _ = self.run_command(policy, "--deploy", "--json", deployer=deployer)

        self.assertEqual(code, 0)
        #
        # Both clusters once each, and every file already in place when the
        # first rollout starts - a cluster is deployed with the whole set.
        #
        self.assertEqual(
            seen,
            [
                ("alpha", ["example.com.pem", "example.net.pem"]),
                ("beta", ["example.com.pem", "example.net.pem"]),
            ],
        )
        document = json.loads(out)
        self.assertEqual(
            document["result"]["deployments"],
            [{"cluster": "alpha", "exit_code": 0}, {"cluster": "beta", "exit_code": 0}],
        )

        seen.clear()
        code, _, _ = self.run_command(policy, "--deploy", deployer=deployer)
        self.assertEqual(code, 0)
        self.assertEqual(seen, [], "an unchanged run must not deploy")

    def test_a_failed_rollout_is_a_failed_run(self) -> None:
        issue(self.live / "example.com", "example.com")
        policy = self.write_config(
            {"example.com": {"source": {"kind": "acme"}, "clusters": ["alpha"]}}
        )

        code, out, _ = self.run_command(policy, "--deploy", "--json", deployer=lambda _: 3)

        self.assertEqual(code, 1)
        document = json.loads(out)
        self.assertEqual(document["outcome"], "failed")
        self.assertIn("not deployed: alpha", document["error"]["message"])
        self.assertTrue((self.dist / "example.com.pem").exists(), "publishing still happened")

    def test_refusals(self) -> None:
        policy = self.write_config(
            {"example.com": {"source": {"kind": "acme"}, "clusters": ["alpha"]}}
        )

        code, out, err = self.run_command(policy, "--certificate", "example.org", "--json")
        self.assertEqual(code, 64)
        self.assertEqual(json.loads(out)["error"]["code"], "bad_input")

        code, out, _ = self.run_command(policy, "--bogus")
        self.assertEqual(code, 64)
        self.assertIn("Usage:", out)

        out, err = io.StringIO(), io.StringIO()
        with mock.patch.object(os, "geteuid", return_value=1000):
            code = command.main(["--json"], policy_path=policy, output_stream=out, error_stream=err)
        self.assertEqual(code, 77)
        self.assertEqual(json.loads(out.getvalue())["error"]["code"], "not_root")


