"""The certificate publisher, held to the Phase 11 gate.

What is proved here, in the gate's own words: a certificate reaches exactly the
targets it names and no others; a run that finds nothing new changes nothing;
a certificate that fails a check leaves no file, whole or partial, under any
target; two runs at once serialise rather than interleave; and `--deploy`
rolls out the clusters that changed, each once, after every file is written.

Certificates are generated by openssl, as in test_cert_list, so the key check
and the expiry check run against real material rather than a stand-in. The
tests run as an ordinary user: the cluster PEM's owner is patched to the test's
own uid and the receiver's fetch account is the test's own user, so ownership
and mode are still set and checked - only the numbers differ from production.
"""

