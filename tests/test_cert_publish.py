"""The certificate publisher, held to the Phase 11 gate.

What is proved here, in the gate's own words: a certificate reaches exactly the
targets it names and no others; a run that finds nothing new changes nothing;
a certificate that fails a check leaves no file, whole or partial, under any
target; two runs at once serialise rather than interleave; and `--deploy`
rolls out the clusters that changed, each once, after every file is written.

Certificates are generated by openssl, as in test_cert_list, so the key check
and the expiry check run against real material rather than a stand-in. The
tests run as an ordinary user: the cluster PEM's owner is patched to the test's
own uid and the receiver's fetch account is the test's own user, so ownership
and mode are still set and checked - only the numbers differ from production.
"""

from __future__ import annotations

import fcntl
import io
import json
import os
import pwd
import subprocess
import tempfile
import threading
import unittest
from pathlib import Path
from unittest import mock

import yaml

from haproxy_mgmt import cert_publish
from haproxy_mgmt.cert_publish import PublishError, publish
from haproxy_mgmt.cli import cert_publish as command
from haproxy_mgmt.config import load_policy, load_runtime_config

BASE = Path(__file__).resolve().parents[1]
ME = pwd.getpwuid(os.getuid()).pw_name


def issue(directory: Path, common_name: str, *, days: int = 30) -> None:
    """certbot's live layout: fullchain.pem and privkey.pem, freshly issued."""

    directory.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            "/usr/bin/openssl",
            "req",
            "-x509",
            "-newkey",
            "ec",
            "-pkeyopt",
            "ec_paramgen_curve:prime256v1",
            "-keyout",
            str(directory / "privkey.pem"),
            "-out",
            str(directory / "fullchain.pem"),
            "-days",
            str(days),
            "-nodes",
            "-subj",
            f"/CN={common_name}",
        ],
        capture_output=True,
        check=True,
    )


def hidden_files(directory: Path) -> list[str]:
    return sorted(path.name for path in directory.iterdir() if path.name.startswith("."))


class Fixture(unittest.TestCase):
    """A manager in a temporary directory: policy, two clusters, one receiver."""

    def setUp(self) -> None:
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name)
        self.live = self.root / "live"
        self.store = self.root / "store"
        self.dist = self.root / "certdist"
        self.receiver_dir = self.root / "receivers" / "lb-01"
        self.lock = self.root / "cert-publish.lock"
        for directory in (self.live, self.store, self.dist, self.receiver_dir):
            directory.mkdir(parents=True)
        patcher = mock.patch.object(cert_publish, "ROOT_UID", os.getuid())
        patcher.start()
        self.addCleanup(patcher.stop)

    def write_config(self, certificates: dict[str, dict[str, object]]) -> Path:
        config_root = self.root / "config"
        publish_root = self.root / "published"
        validation = self.root / "validation"
        for directory in (config_root, publish_root, validation):
            directory.mkdir(exist_ok=True)
        (validation / "validation.pem").write_text("dummy PEM\n", encoding="utf-8")

        #
        # The loader holds a cluster to carrying at least one certificate and
        # to a default among them, so the clusters are the ones the registry
        # names and each defaults to the first certificate naming it.
        #
        clusters = yaml.safe_load((BASE / "examples/clusters.yaml").read_text())
        template = dict(clusters["clusters"]["alpha"])
        clusters["clusters"] = {}
        for cluster_id in ("alpha", "beta"):
            carried = [
                certificate_id
                for certificate_id, raw in certificates.items()
                if cluster_id in (raw.get("clusters") or [])  # type: ignore[union-attr]
            ]
            if not carried:
                continue
            entry = dict(template)
            entry["config_path"] = str(config_root / cluster_id)
            entry["publish_path"] = str(publish_root / cluster_id)
            entry["validation_certs"] = str(validation)
            entry.pop("certificate_ids", None)
            entry["default_certificate"] = carried[0]
            (config_root / cluster_id).mkdir(exist_ok=True)
            clusters["clusters"][cluster_id] = entry
        (self.root / "clusters.yaml").write_text(yaml.safe_dump(clusters), encoding="utf-8")

        registry = {
            "schema_version": 1,
            "receivers": {"lb-01": {"path": str(self.receiver_dir), "owner": ME}},
            "certificates": certificates,
        }
        (self.root / "certificates.yaml").write_text(yaml.safe_dump(registry), encoding="utf-8")

        policy = {
            "schema_version": 1,
            "cluster_file": str(self.root / "clusters.yaml"),
            "config_root": str(config_root),
            "publish_root": str(publish_root),
            "validation_certs_root": str(validation),
            "certificate_root": str(self.dist),
            "certificate_registry": str(self.root / "certificates.yaml"),
        }
        policy_path = self.root / "runtime-policy.yaml"
        policy_path.write_text(yaml.safe_dump(policy), encoding="utf-8")
        return policy_path

    def run_publish(self, policy_path: Path, **options: object) -> cert_publish.Report:
        policy = load_policy(policy_path, require_secure=False)
        runtime = load_runtime_config(policy, require_secure=False)
        return publish(
            runtime,
            policy,
            live=self.live,
            store=self.store,
            lock_path=self.lock,
            **options,  # type: ignore[arg-type]
        )

    def run_command(self, policy_path: Path, *argv: str, **options: object) -> tuple[int, str, str]:
        out, err = io.StringIO(), io.StringIO()
        code = command.main(
            list(argv),
            policy_path=policy_path,
            output_stream=out,
            error_stream=err,
            require_secure=False,
            require_root=False,
            live=self.live,
            store=self.store,
            lock_path=self.lock,
            **options,  # type: ignore[arg-type]
        )
        return code, out.getvalue(), err.getvalue()


class ExactTargets(Fixture):
    def test_a_certificate_reaches_its_targets_in_each_targets_format(self) -> None:
        issue(self.live / "example.com-wildcard", "example.com")
        policy = self.write_config(
            {
                "example.com": {
                    "source": {"kind": "acme", "lineage": "example.com-wildcard"},
                    "clusters": ["alpha"],
                    "receivers": ["lb-01"],
                }
            }
        )

        report = self.run_publish(policy)

        [entry] = report.certificates
        self.assertEqual(entry.status, "published")
        self.assertEqual(
            [(t.kind, t.name, t.changed) for t in entry.targets],
            [("cluster", "alpha", True), ("receiver", "lb-01", True)],
        )
        combined = self.dist / "example.com.pem"
        key = (self.live / "example.com-wildcard" / "privkey.pem").read_bytes()
        chain = (self.live / "example.com-wildcard" / "fullchain.pem").read_bytes()
        self.assertEqual(combined.read_bytes(), key + chain)
        self.assertEqual(combined.stat().st_mode & 0o777, 0o640)
        self.assertEqual((self.receiver_dir / "fullchain.pem").read_bytes(), chain)
        self.assertEqual((self.receiver_dir / "privkey.pem").read_bytes(), key)
        self.assertEqual((self.receiver_dir / "privkey.pem").stat().st_mode & 0o777, 0o600)
        self.assertEqual(report.changed_clusters, ("alpha",))

    def test_no_spill_between_targets(self) -> None:
        #
        # The gate's invariant: "exactly the targets chosen, and no others".
        # One certificate per cluster, one for the receiver only, and each
        # directory ends up holding precisely its own.
        #
        issue(self.live / "example.com", "example.com")
        issue(self.live / "example.net", "example.net")
        issue(self.live / "lb-01.example.org", "lb-01.example.org")
        policy = self.write_config(
            {
                "example.com": {"source": {"kind": "acme"}, "clusters": ["alpha"]},
                "example.net": {"source": {"kind": "acme"}, "clusters": ["alpha", "beta"]},
                "lb-01.example.org": {"source": {"kind": "acme"}, "receivers": ["lb-01"]},
            }
        )

        report = self.run_publish(policy)

        self.assertEqual({e.status for e in report.certificates}, {"published"})
        self.assertEqual(
            sorted(p.name for p in self.dist.iterdir()), ["example.com.pem", "example.net.pem"]
        )
        self.assertEqual(
            sorted(p.name for p in self.receiver_dir.iterdir()), ["fullchain.pem", "privkey.pem"]
        )
        self.assertIn(b"BEGIN CERTIFICATE", (self.receiver_dir / "fullchain.pem").read_bytes())
        self.assertEqual(report.changed_clusters, ("alpha", "beta"))

    def test_only_selects_named_certificates(self) -> None:
        issue(self.live / "example.com", "example.com")
        issue(self.live / "example.net", "example.net")
        policy = self.write_config(
            {
                "example.com": {"source": {"kind": "acme"}, "clusters": ["alpha"]},
                "example.net": {"source": {"kind": "acme"}, "clusters": ["beta"]},
            }
        )

        report = self.run_publish(policy, only=["example.net"])

        self.assertEqual([e.certificate_id for e in report.certificates], ["example.net"])
        self.assertEqual([p.name for p in self.dist.iterdir()], ["example.net.pem"])
        with self.assertRaises(PublishError) as caught:
            self.run_publish(policy, only=["example.org"])
        self.assertEqual(caught.exception.code, "bad_input")


class Idempotence(Fixture):
    def test_a_second_run_touches_nothing(self) -> None:
        issue(self.live / "example.com", "example.com")
        policy = self.write_config(
            {
                "example.com": {
                    "source": {"kind": "acme"},
                    "clusters": ["alpha"],
                    "receivers": ["lb-01"],
                }
            }
        )
        self.run_publish(policy)
        before = {
            path: path.stat().st_ino
            for path in (
                self.dist / "example.com.pem",
                self.receiver_dir / "fullchain.pem",
                self.receiver_dir / "privkey.pem",
            )
        }

        report = self.run_publish(policy)

        [entry] = report.certificates
        self.assertEqual(entry.status, "unchanged")
        self.assertFalse(any(t.changed for t in entry.targets))
        self.assertEqual(report.changed_clusters, ())
        for path, inode in before.items():
            self.assertEqual(path.stat().st_ino, inode, f"{path.name} was rewritten")

    def test_a_renewal_is_published_and_the_old_file_replaced_in_place(self) -> None:
        issue(self.live / "example.com", "example.com")
        policy = self.write_config(
            {"example.com": {"source": {"kind": "acme"}, "clusters": ["alpha"]}}
        )
        self.run_publish(policy)
        old = (self.dist / "example.com.pem").read_bytes()
        issue(self.live / "example.com", "example.com")

        report = self.run_publish(policy)

        self.assertEqual(report.certificates[0].status, "published")
        self.assertNotEqual((self.dist / "example.com.pem").read_bytes(), old)
        self.assertEqual(hidden_files(self.dist), [])


class NothingHalfWritten(Fixture):
    def test_a_key_that_does_not_match_publishes_nothing(self) -> None:
        issue(self.live / "example.com", "example.com")
        issue(self.live / "other", "other")
        (self.live / "example.com" / "privkey.pem").write_bytes(
            (self.live / "other" / "privkey.pem").read_bytes()
        )
        policy = self.write_config(
            {
                "example.com": {
                    "source": {"kind": "acme"},
                    "clusters": ["alpha"],
                    "receivers": ["lb-01"],
                }
            }
        )

        report = self.run_publish(policy)

        [entry] = report.certificates
        self.assertEqual(entry.status, "failed")
        self.assertEqual(entry.error[0] if entry.error else None, "key_mismatch")
        self.assertEqual(list(self.dist.iterdir()), [])
        self.assertEqual(list(self.receiver_dir.iterdir()), [])

    def test_a_certificate_about_to_expire_leaves_the_published_one_alone(self) -> None:
        issue(self.live / "example.com", "example.com", days=30)
        policy = self.write_config(
            {"example.com": {"source": {"kind": "acme"}, "clusters": ["alpha"]}}
        )
        self.run_publish(policy)
        good = (self.dist / "example.com.pem").read_bytes()
        issue(self.live / "example.com", "example.com", days=3)

        report = self.run_publish(policy)

        self.assertEqual(report.certificates[0].status, "failed")
        self.assertEqual(report.certificates[0].error[0], "certificate_expiring")  # type: ignore[index]
        self.assertEqual((self.dist / "example.com.pem").read_bytes(), good)

    def test_a_missing_receiver_directory_stops_the_whole_certificate(self) -> None:
        #
        # Targets are resolved before the first write. A certificate that
        # names a receiver whose directory is gone is not published to its
        # cluster either: half of "exactly these targets" is not a result.
        #
        issue(self.live / "example.com", "example.com")
        policy = self.write_config(
            {
                "example.com": {
                    "source": {"kind": "acme"},
                    "clusters": ["alpha"],
                    "receivers": ["lb-01"],
                }
            }
        )
        self.receiver_dir.rmdir()

        report = self.run_publish(policy)

        self.assertEqual(report.certificates[0].status, "failed")
        self.assertEqual(report.certificates[0].error[0], "target_missing")  # type: ignore[index]
        self.assertEqual(list(self.dist.iterdir()), [])

    def test_one_failure_does_not_stop_the_next_certificate(self) -> None:
        issue(self.live / "example.net", "example.net")
        policy = self.write_config(
            {
                "example.com": {"source": {"kind": "acme"}, "clusters": ["alpha"]},
                "example.net": {"source": {"kind": "acme"}, "clusters": ["alpha"]},
            }
        )

        report = self.run_publish(policy)

        statuses = {e.certificate_id: e.status for e in report.certificates}
        self.assertEqual(statuses, {"example.com": "failed", "example.net": "published"})
        self.assertEqual(report.certificates[0].error[0], "source_missing")  # type: ignore[index]
        self.assertEqual([p.name for p in self.dist.iterdir()], ["example.net.pem"])


